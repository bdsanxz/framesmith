//! The centreline pieces of every glyph of the test font, written for this font on the design grid of
//! `docs/spec/test-font.md`, section 3. Units are thousandths of the em. A straight piece joins two
//! points. An arc is part of a circle, from one angle to another in degrees: counter-clockwise when
//! `to` is greater than `from`, clockwise when it is less. A straight piece whose two points are equal
//! is a dot.

/// One piece of the centreline of a glyph.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Piece {
    /// A straight stroke from `(x1, y1)` to `(x2, y2)`.
    Line { x1: i32, y1: i32, x2: i32, y2: i32 },
    /// A circular arc of radius `r` about `(cx, cy)`, from the angle `from` to the angle `to`.
    Arc { cx: i32, cy: i32, r: i32, from: i32, to: i32 },
}

const fn line(x1: i32, y1: i32, x2: i32, y2: i32) -> Piece {
    Piece::Line { x1, y1, x2, y2 }
}

const fn arc(cx: i32, cy: i32, r: i32, from: i32, to: i32) -> Piece {
    Piece::Arc { cx, cy, r, from, to }
}

